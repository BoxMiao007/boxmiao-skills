const pick = (arr) => arr[Math.floor(rnd() * arr.length)];

function ts(i) {
  const totalSec = Math.floor(i / 3);
  const h = Math.floor(totalSec / 3600);
  const m = Math.floor((totalSec % 3600) / 60);
  const s = totalSec % 60;
  const cs = (i % 3) * 33;
  const t = (x) => String(x).padStart(2, '0');
  return `${h}:${t(m)}:${t(s)}.${t(cs)}`;
}
function endTs(i) {
  const totalSec = Math.floor(i / 3) + 3;
  const h = Math.floor(totalSec / 3600);
  const m = Math.floor((totalSec % 3600) / 60);
  const s = totalSec % 60;
  const cs = (i % 3) * 33;
  const t = (x) => String(x).padStart(2, '0');
  return `${h}:${t(m)}:${t(s)}.${t(cs)}`;
}

